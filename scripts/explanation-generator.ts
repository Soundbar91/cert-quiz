function firstMatch(text: string, rules: Rule[]) {
  return rules.find(([pattern]) => pattern.test(text))?.[1];
}

function contextualOptionFact(question: Question, choice: string) {
  if (/ls 옵션/.test(question.question)) {
    if (/^-a|^-a:/.test(choice)) return "-a는 점(.)으로 시작하는 숨김 파일을 포함합니다.";
    if (/^-l|^-l:/.test(choice)) return "-l은 권한·소유자·크기·시각 등을 긴 형식으로 출력하며 대화형 옵션이 아닙니다.";
    if (/^-R|^-R:/.test(choice)) return "-R은 하위 디렉터리를 재귀적으로 출력합니다.";
    if (/^-F|^-F:/.test(choice)) return "-F는 파일 종류에 따라 /, *, @ 같은 표시를 붙입니다.";
  }
  if (/diff 옵션/.test(question.question)) {
    if (/^-i/.test(choice)) return "diff -i는 대소문자 차이를 무시하므로 '구별한다'는 설명은 반대입니다.";
    if (/^-b/.test(choice)) return "diff -b는 연속된 공백 수의 차이를 무시합니다.";
    if (/^-e/.test(choice)) return "diff -e는 차이를 적용할 수 있는 ed 스크립트를 만듭니다.";
    if (/^-w/.test(choice)) return "diff -w는 모든 공백 차이를 무시합니다.";
  }
  if (/rm에서|rm 명령/.test(question.question)) {
    if (choice === "-i") return "-i는 삭제 전에 확인을 요청하는 대화형 옵션입니다.";
    if (choice === "-f") return "-f는 확인 없이 강제 삭제합니다.";
    if (choice === "-r") return "-r은 디렉터리 하위를 재귀적으로 삭제합니다.";
    if (choice === "-v") return "-v는 처리한 경로를 자세히 출력합니다.";
  }
  if (/usermod.*옵션/.test(question.question)) {
    if (choice === "-d") return "-d는 홈 디렉터리 경로를 지정합니다.";
    if (choice === "-g") return "-g는 기본 그룹을 지정합니다.";
    if (choice === "-s") return "-s는 기존 사용자가 로그인할 때 실행될 기본 셸의 경로를 지정합니다.";
    if (choice === "-u") return "-u는 숫자 UID를 지정합니다.";
    if (choice === "-e") return "-e는 기존 사용자 계정이 만료되는 날짜를 지정합니다.";
    if (choice === "-l") return "-l은 기존 사용자의 로그인 이름을 새 이름으로 변경합니다.";
  }
  if (/rdate/.test(question.question)) {
    if (choice === "-s") return "-s는 원격 시각을 로컬 시스템에 설정합니다.";
    if (choice === "-p") return "-p는 원격 시각을 설정하지 않고 출력합니다.";
  }

  return firstMatch(choice, knowledgeRules) ?? firstMatch(choice, optionRules);
}

function coreKnowledge(question: Question) {
  const fullText = `${question.question} ${question.choices.join(" ")}`;
  return (
    coreOverrides[question.id] ??
    firstMatch(fullText, knowledgeRules) ??
    "이 문항은 각 선택지의 실제 정의와 동작을 구분하는 문제입니다. 이름이 비슷한 명령도 입력·출력 대상과 시스템에 주는 영향이 다르므로 기능을 기준으로 판단해야 합니다."
  );
}

export function getQuestionExplanation(question: Question): QuestionExplanation {
  const correctChoice = question.choices[question.answer];
  const asksForException =
    /틀린|아닌|않은|없는|어려운|관련이 적은|거리가 먼|다른 것은/.test(
      question.question,
    );
  const correctFact =
    contextualOptionFact(question, correctChoice) ?? coreKnowledge(question);

  const answerReason = asksForException
    ? `문제는 틀리거나 해당하지 않는 항목을 요구합니다. ${correctFact}`
    : correctFact;

  const choiceReasons = question.choices.map((choice, index) => {
    const fact = contextualOptionFact(question, choice);
    const isAnswer = index === question.answer;

    if (isAnswer) {
      return asksForException
        ? `정답 — ${
            fact ??
            `${coreKnowledge(question)} 따라서 “${choice}”가 틀리거나 해당하지 않는 선택지입니다.`
          }`
        : `정답 — ${fact ?? correctFact}`;
    }

    if (asksForException) {
      return `정답이 아님 — ${
        fact ??
        `“${choice}”는 문제의 제외 대상이 아닌 올바른 설명입니다. ${coreKnowledge(question)}`
      }`;
    }

    return `오답 — ${
      fact ??
      `“${choice}”는 이 문항에서 묻는 기능·정의와 다릅니다. ${coreKnowledge(question)}`
    }`;
  }) as [string, string, string, string];

  return { core: coreKnowledge(question), answerReason, choiceReasons };
}
